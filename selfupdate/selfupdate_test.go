func TestSettleClearsMarkerAndStopsRollback(t *testing.T) {
	requireUnix(t)
	p := testPaths(t)
	fakeBin(t, p.Current, "new", 0)
	fakeBin(t, p.Old, "old", 0)
	if err := writeMarker(p.Marker, marker{From: "0.3.7", To: "0.3.8", Attempts: 2}); err != nil {
		t.Fatal(err)
	}

	settle(p)

	if _, err := os.Stat(p.Marker); !os.IsNotExist(err) {
		t.Fatal("stable update marker was not removed")
	}
	// Settled marker removal prevents later normal starts from accumulating rollback attempts.
	if _, ok := readMarker(p.Marker); ok {
		t.Error("marker read should fail")
	}
	// Preserve the backup for deliberate rollback.
	if _, err := os.Stat(p.Old); err != nil {
		t.Error("stable update must retain backup")
	}
}

func TestSettleIsNoopWithoutMarker(t *testing.T) {
	requireUnix(t)
	p := testPaths(t)
	fakeBin(t, p.Current, "cur", 0)
	settle(p) // Ordinary startup neither panics nor changes update files.
	if _, err := os.Stat(p.Current); err != nil {
		t.Error("settling without a marker must not alter files")
	}
}
