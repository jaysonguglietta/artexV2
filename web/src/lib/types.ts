// LLM retry policy.
// Each retry layer has two controls. Zero means unconfigured for both:
// attempts: zero uses defaults, -1 disables the layer, positive values set the retry count.
// interval_ms: zero uses exponential backoff, positive values select a fixed interval.
export interface LLMRetryRule {
  attempts: number;
  interval_ms: number;
}

// Three endpoint-specific retry layers can be overridden by an individual profile.
export interface LLMRetryOverride {
  connect: LLMRetryRule; // Connection retry before streaming: resets, timeouts, 429 and 5xx.
  empty: LLMRetryRule; // Completed response with no content, supported for OpenAI format.
  stream: LLMRetryRule; // Same-provider interrupted-stream replay before any output was delivered.
}

// Global policy provides defaults for those layers plus two global-only layers:
// breaker: trip after consecutive transient failures, then wait a fixed cooldown.
// intent: rerun a whole worker intent after a model_error result.
export interface LLMRetryPolicy extends LLMRetryOverride {
  breaker: LLMRetryRule;
  intent: LLMRetryRule;
}

