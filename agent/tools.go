// intentItem represents one direction in a single or batch add_intent call.
type intentItem struct {
	Summary   string            `json:"summary"`
	AssetIDs  []json.RawMessage `json:"asset_ids"`
	ParentIDs []json.RawMessage `json:"parent_ids"`
	Priority  int               `json:"priority"`
}

// addOneIntent validates existing fact/finding parent anchors before creating the node and lineage. Other intent/goal/hint kinds cannot be parents. Empty top-level parents fall back to the origin fact, keeping planning grounded in known evidence.
func (t *ToolSet) addOneIntent(it intentItem) (int64, error) {
	if strings.TrimSpace(it.Summary) == "" {
		return 0, fmt.Errorf("summary cannot be empty")
	}
	// Validate anchors before insertion so invalid parents cannot leave orphan intents.
	parents := pidList(it.ParentIDs)
	for _, pidv := range parents {
		n, err := t.ts.GetNodeWithSources(pidv)
		if err != nil || n == nil {
			return 0, fmt.Errorf("parent_id %d is absent from this task and directly linked tasks. parent_ids must reference existing fact/finding nodes; omit them for a new top-level direction", pidv)
		}
		if n.Kind != db.KindFact && n.Kind != db.KindFinding {
			return 0, fmt.Errorf("parent_id %d is a %q node and cannot anchor an intent. Use confirmed fact/finding nodes, not intents, goals, or hints; omit parent_ids for a new top-level direction", pidv, n.Kind)
		}
	}
	priority := it.Priority
	if priority == 0 {
		priority = 5
	}
	anchors := pidList(it.AssetIDs)
	// Refuse intents whose linked assets match system asset interception rules.
	if t.as != nil && len(anchors) > 0 {
		hits, err := t.as.CheckAssetsIntercept(t.taskID, anchors)
		if err != nil {
			return 0, fmt.Errorf("Asset intercept validation failed: %w", err)
		}
		if len(hits) > 0 {
			var b strings.Builder
			fmt.Fprintf(&b, "Assets bound to intent [%s] failed test-scope validation. Stop testing the affected assets:", it.Summary)
			for _, h := range hits {
				fmt.Fprintf(&b, "\n - %s", h.Describe())
			}
			return 0, fmt.Errorf("%s", b.String())
		}
	}
	payload := map[string]any{"summary": it.Summary}
	if len(anchors) > 0 {
		payload["asset_ids"] = anchors
	}
	id, err := t.ts.AddIntent(payload, priority, anchors, "planner")
	if err != nil {
		return 0, err
	}
	// upstream lineage: link each (validated) fact/finding parent → this intent, so
	// "multiple facts combine into one new intent" is expressible.
	for _, parent := range parents {
		_ = t.ts.Link(parent, db.RelDerivedFrom, id)
	}
	// a top-level intent (no explicit parent) connects to the origin fact, so every
	// intent still traces back to a fact node — at task start the only fact is the
	// origin, and the first intents derive from it.
	if len(parents) == 0 {
		if origin, _ := t.ts.OriginFactID(); origin > 0 {
			_ = t.ts.Link(origin, db.RelDerivedFrom, id)
		}
	}
	return id, nil
}

func (t *ToolSet) addIntent() actool.CoreTool {
	return t.writeExpTool("add_intent", "Create exploration directions in the frontier and link their lineage. Intents are open directions, not fixed categories; summarize what to investigate, verify, or exploit in one sentence.\n"+
		"Prefer batching: submit new directions from one round in a single intents array. Returned ids preserve length/order, with id=0 for failures and details in errors. For one direction, omit intents and use top-level summary.",
		obj(map[string]any{
			"intents":    map[string]any{"type": "array", "description": "Preferred new-direction array, processed in order. Each item uses summary/asset_ids/parent_ids/priority as below; returned ids preserve length and order.", "items": map[string]any{"type": "object"}},
			"summary":    str("Single direction: one sentence stating what to do and why; it need not depend on an asset ID."),
			"asset_ids":  map[string]any{"type": "array", "items": map[string]any{"type": "integer"}, "description": "Target asset IDs from list_assets, not exploration node IDs; include all concrete sites/endpoints/parameters/hosts involved. These structured targets support coverage, deduplication, and asset lineage. Omit only for global reconnaissance without a concrete target."},
			"parent_ids": map[string]any{"type": "array", "items": map[string]any{"type": "integer"}, "description": "Optional upstream confirmed fact/finding node IDs that produced this direction. Never use intent/goal/hint IDs. Include all contributing facts; omit for new top-level reconnaissance, which attaches to the task origin fact."},
			"priority":   intp("Priority 0-10; default 5"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			var a struct {
				Intents    []intentItem `json:"intents"`
				intentItem              // Single-entry fields live at the top level: summary, asset_ids, parent_ids and priority.
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Intents) > 0
			items := a.Intents
			if !batch {
				items = []intentItem{a.intentItem}
			}

			ids := make([]int64, len(items))
			errs := map[string]string{}
			createdAny := false
			for i, it := range items {
				id, err := t.addOneIntent(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
				createdAny = true
			}

			// A human-injected main-agent intent revives a completed goalless task so workers can claim it. Only main-agent Chat wires resumeTask; planner calls remain a no-op here. The open intent already exists before revival.
			if createdAny && t.resumeTask != nil {
				t.resumeTask()
			}

			if !batch { // Preserve the single-entry response shape.
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("intent created: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

